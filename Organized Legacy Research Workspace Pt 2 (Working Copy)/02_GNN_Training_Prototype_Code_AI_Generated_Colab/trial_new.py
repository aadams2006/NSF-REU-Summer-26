def train_model(model, train_loader, val_loader, optimizer, criterion,
                num_epochs=200, device='cpu', patience=20):
    """
    Two-phase training:
      Phase 1 — large LR (exploration): quickly scans the loss landscape and
                escapes local minima to find the Goldilocks region.
      Phase 2 — small LR (fine-tune):  converges precisely from that region.

    The optimizer is re-initialised between phases so the momentum/state
    from the noisy large-LR phase doesn't carry over and destabilise fine-tuning.
    """
    model.to(device)

    train_losses = []
    val_losses   = []
    best_val_loss      = float('inf')
    best_model_state   = None
    patience_counter   = 0

    phases = [
        ("Phase 1 — Exploration (large LR)", LR_PHASE1,  EPOCHS_PHASE1),
        ("Phase 2 — Fine-tune  (small LR)",  LR_PHASE2,  EPOCHS_PHASE2),
    ]

    global_epoch = 0

    for phase_name, lr, phase_epochs in phases:
        print(f"\n{'='*60}")
        print(f"🚀 {phase_name}  |  LR={lr}  |  Epochs={phase_epochs}")
        print(f"{'='*60}")

        # Fresh optimizer each phase — prevents stale momentum from phase 1
        # polluting the precise descent in phase 2
        phase_optimizer = Adam(model.parameters(), lr=lr, weight_decay=1e-5)

        patience_counter = 0  # Reset patience per phase

        for epoch in range(phase_epochs):
            # ── Training ──────────────────────────────────────────────────────
            model.train()
            train_loss = 0
            for batch in train_loader:
                batch = batch.to(device)
                phase_optimizer.zero_grad()
                out  = model(batch)
                loss = criterion(out, batch.y.unsqueeze(1))
                loss.backward()
                phase_optimizer.step()
                train_loss += loss.item() * batch.num_graphs

            train_loss /= len(train_loader.dataset)
            train_losses.append(train_loss)

            # ── Validation ────────────────────────────────────────────────────
            model.eval()
            val_loss = 0
            with torch.no_grad():
                for batch in val_loader:
                    batch = batch.to(device)
                    out   = model(batch)
                    loss  = criterion(out, batch.y.unsqueeze(1))
                    val_loss += loss.item() * batch.num_graphs

            val_loss /= len(val_loader.dataset)
            val_losses.append(val_loss)

            # ── Best model checkpoint ─────────────────────────────────────────
            if val_loss < best_val_loss:
                best_val_loss    = val_loss
                patience_counter = 0
                best_model_state = {k: v.clone() for k, v in model.state_dict().items()}
            else:
                patience_counter += 1

            global_epoch += 1
            if global_epoch % 20 == 0:
                print(f'  Epoch {global_epoch}/{num_epochs} '
                      f'| Train: {train_loss:.6f} | Val: {val_loss:.6f}'
                      f'{"  ★" if patience_counter == 0 else ""}')

            if patience_counter >= patience:
                print(f'  ⏹️  Early stopping at epoch {global_epoch}')
                break

        print(f"  ✅ {phase_name} done. Best val loss so far: {best_val_loss:.6f}")

    # Restore best weights found across both phases
    model.load_state_dict(best_model_state)

    return {
        'train_losses': train_losses,
        'val_losses':   val_losses,
        'best_val_loss': best_val_loss
    }

