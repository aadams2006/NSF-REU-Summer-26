def load_lattice_data(folder_path):
    """
    Load a single lattice sample from CSV files.
    """
    # Load node features
    node_features_path = os.path.join(folder_path, 'node_features.csv')
    nodes_df = pd.read_csv(node_features_path)
    node_features = nodes_df[['x', 'y']].values.astype(np.float32)

    # Load adjacency matrix
    adj_path = os.path.join(folder_path, 'adjacency_area.csv')
    adj_df = pd.read_csv(adj_path, index_col=0)
    adj_matrix = adj_df.values

    # Convert to edge list (bidirectional)
    edge_list = []
    for i in range(adj_matrix.shape[0]):
        for j in range(i+1, adj_matrix.shape[1]):
            if adj_matrix[i, j] == 1:
                edge_list.append([i, j])
                edge_list.append([j, i])

    edge_index = torch.tensor(edge_list, dtype=torch.long).t().contiguous()

    # Load stiffness
    stiffness_path = os.path.join(folder_path, 'lattice_stiffness.csv')
    stiffness_df = pd.read_csv(stiffness_path)
    stiffness = stiffness_df.iloc[0, 0]

    # Create graph
    data = Data(
        x=torch.tensor(node_features, dtype=torch.float32),
        edge_index=edge_index,
        y=torch.tensor([stiffness], dtype=torch.float32)
    )

    return data


