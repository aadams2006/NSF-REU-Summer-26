def evaluate_model(model, data_loader, device='cpu'):
    """
    Evaluate model performance.
    """
    model.eval()
    model.to(device)

    predictions = []
    ground_truth = []

    with torch.no_grad():
        for batch in data_loader:
            batch = batch.to(device)
            out = model(batch)
            predictions.extend(out.cpu().numpy().flatten())
            ground_truth.extend(batch.y.cpu().numpy().flatten())

    predictions = np.array(predictions)
    ground_truth = np.array(ground_truth)

    # Calculate metrics
    mse = np.mean((predictions - ground_truth) ** 2)
    rmse = np.sqrt(mse)
    mae = np.mean(np.abs(predictions - ground_truth))
    relative_errors = np.abs((predictions - ground_truth) / ground_truth) * 100
    mean_relative_error = np.mean(relative_errors)

    metrics = {
        'MSE': mse,
        'RMSE': rmse,
        'MAE': mae,
        'Mean Relative Error (%)': mean_relative_error
    }

    return predictions, ground_truth, metrics

