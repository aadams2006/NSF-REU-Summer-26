class SimpleGNN(nn.Module):
    """
    Two-layer Graph Convolutional Network for lattice stiffness prediction.
    """
    def __init__(self, input_dim, hidden_dim=32, output_dim=1):
        super(SimpleGNN, self).__init__()

        # First graph convolution layer
        self.conv1 = GCNConv(input_dim, hidden_dim)
        self.bn1 = nn.BatchNorm1d(hidden_dim)

        # ← ADD THIS: Second graph convolution layer
        self.conv2 = GCNConv(hidden_dim, hidden_dim)
        self.bn2 = nn.BatchNorm1d(hidden_dim)

        # Output layer
        self.fc_out = nn.Linear(hidden_dim, output_dim)
        self.dropout = nn.Dropout(0.1)

    def forward(self, data):
        x, edge_index, batch = data.x, data.edge_index, data.batch

        # First layer: Graph convolution + activation
        x = self.conv1(x, edge_index)
        x = self.bn1(x)
        x = F.relu(x)
        x = self.dropout(x)

        # ← ADD THIS: Second layer
        x = self.conv2(x, edge_index)
        x = self.bn2(x)
        x = F.relu(x)
        x = self.dropout(x)

        # Global pooling
        x = global_mean_pool(x, batch)

        # Final prediction
        out = self.fc_out(x)

        return out

